#pragma once

// Прямоугольная область на экране.
// Используется для координат и размеров элементов интерфейса.
struct Rectangle {
    float x = 0.0f;      // координата левого верхнего угла по X
    float y = 0.0f;      // координата левого верхнего угла по Y
    float width = 0.0f;  // ширина прямоугольника
    float height = 0.0f; // высота прямоугольника
};