#pragma once

// Внутреннее состояние игры вынесено отдельно, потому что оно используется
// в GameWorld, Game, Application и Renderer без лишней зависимости от GameWorld.h.

// Внутреннее состояние игровой логики.
enum class GameState {
    Playing,        // уровень сейчас играется
    PlayerDying,    // игрок погибает, показывается взрыв
    LevelCompleted, // уровень пройден, идёт пауза перед следующим
    GameOver,       // все жизни потеряны
    Win             // все уровни пройдены
};