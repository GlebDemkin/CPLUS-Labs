#pragma once

// Перечисление клавиш, которые используются для управления меню.
// Оно нужно, чтобы в MenuSystem работать не с числовыми кодами GLFW,
// а с понятными значениями: KeyCode::Up, KeyCode::Enter и т.д.

// enum class — строго типизированное перечисление.
// Переменная типа KeyCode может принимать только значения из списка ниже.
enum class KeyCode
{
    Unknown, // неизвестная клавиша
    Up,      // стрелка вверх
    Down,    // стрелка вниз
    Enter,   // выбор пункта
    Delete,  // возврат назад
    Escape   // закрытие меню
};